export function t(locale: Locale, key: string, vars?: Record<string, string>): string {
  let value = translations[locale]?.[key] ?? translations.pl[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, v);
    }
  }
  return value;
}
